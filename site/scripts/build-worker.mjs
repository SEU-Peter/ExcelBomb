import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const core=fs.readFileSync(path.join(root,'dist/core.js'),'utf8').replace(/^export /gm,'');
const runtime=fs.readFileSync(path.join(root,'src/worker-runtime.js'),'utf8');
const preserve=fs.readFileSync(path.join(root,'dist/preserve.js'),'utf8').replace(/^export /gm,'').replace(/^import .*;\r?\n/gm,'');
fs.writeFileSync(path.join(root,'dist/worker.js'),`// Generated by scripts/build-worker.mjs; edit core.js, preserve.js or src/worker-runtime.js.\nif(typeof XLSX==='undefined')importScripts('vendor/xlsx.full.min.js','vendor/jszip.min.js');\n${core}\n${preserve}\n${runtime}`);
console.log('Background worker built.');
